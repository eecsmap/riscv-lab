#!/bin/bash
# Regenerates TABLES.md and SUMMARY.txt from p0model.py (deterministic; no randomness in the model).
set -u; cd "$(dirname "$0")"
python3 p0model.py > SUMMARY.txt; rc=$?
{
  echo "# PIPE-P0 control model — cycle tables (correct design)"
  echo
  echo "Generated by \`gen-tables.sh\` from \`p0model.py\`. Each row is the START-of-cycle state; \`events\` are what happens in that cycle."
  echo "Legend: F1/F2 \`w<n>:<state>\` (lo = TLB/cache lookup, re = ready, wa = waiting for the walker, rf = refill, nc = uncached wait);"
  echo "FB \`w<n>.<next slot>\`; stage cells \`<pc><kind>\` (A alu, L load, S store, B branch, C csr, M mret, E ecall, H halt, I synthetic interrupt token),"
  echo "\`!\` = interrupt token, \`:tlb/walk/iss/wait/done\` = MEM progress; port = owner (WF/WM walker, F refill, NC uncached fetch, M data)"
  echo "+ \`k\` killed + \`v\` valid-not-yet-accepted / \`F\` fired-awaiting-response."
  echo
  echo "## Summary: every scenario on the correct design, and every mutation (each must FAIL for its own reason)"
  echo; cat SUMMARY.txt; echo
  for s in wb-once two-flush walker-deadlock irq-no-input irq-vs-older-fault frontend serial-drain-T2 serial-drain-T6 serial-drain-T18 store-under-trap load-use spec-uncached-fetch retire-assoc; do
    python3 p0model.py --table $s --hi 70; echo
  done
} > TABLES.md
echo "gen-tables rc=$rc"; exit $rc
