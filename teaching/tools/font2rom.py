#!/usr/bin/env python3
"""Generate teaching/mcu0/mcu_vga_font.v, the VGA text mode's character ROM, from teaching/oled/font8x8.h.

    python3 teaching/tools/font2rom.py teaching/oled/font8x8.h teaching/mcu0/mcu_vga_font.v [font_rom.hex]

The optional third file is the same ROM as $readmemh text, for the testbench's own reference renderer.

font8x8.h stores a glyph as 8 column bytes (bit y = row y, as the OLED wants it). The VGA beam draws a row at a time,
so the ROM stores 8 row bytes per character instead: address {char, row}, bit 7 = the leftmost pixel.

  0x20..0x7F  the font8x8.h glyphs
  0x80..0x8F  quarter blocks: bit 0 lights the top-left 4 x 4 quarter, bit 1 top-right, bit 2 bottom-left,
              bit 3 bottom-right -- 200 x 150 "pixels" in text mode, two colours per character cell
  others      blank
The ROM is a case statement, so iverilog and Vivado both read it without a memory-file path.
"""
import os
import re
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    hexfile = sys.argv[3] if len(sys.argv) > 3 else None
    text = open(src).read()
    body = text[text.index("font8x8[96 * 8] = {"):]
    body = body[:body.index("};")]
    body = re.sub(r"//[^\n]*", "", body)          # the comments name the characters, and contain hex-looking text
    cols = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    if len(cols) != 96 * 8:
        sys.exit(f"font2rom: expected 768 bytes in {src}, found {len(cols)}")

    rom = [0] * (256 * 8)
    for i in range(96):
        g = cols[i * 8:i * 8 + 8]
        for y in range(8):
            rom[(0x20 + i) * 8 + y] = sum(((g[x] >> y) & 1) << (7 - x) for x in range(8))
    for q in range(16):
        for y in range(8):
            left = 0xF0 if q & (1 if y < 4 else 4) else 0
            right = 0x0F if q & (2 if y < 4 else 8) else 0
            rom[(0x80 + q) * 8 + y] = left | right

    out = [
        "// GENERATED by teaching/tools/font2rom.py from teaching/oled/font8x8.h -- do not edit; run the script again.",
        "// The VGA text mode's character ROM: address {char, row}, bit 7 = leftmost pixel. 0x20..0x7F Digilent's",
        "// ChrFont0 glyphs (MIT licence, see font8x8.h), 0x80..0x8F quarter blocks, everything else blank.",
        "// A registered read, so Vivado maps it to one block RAM.",
        "`timescale 1ns/1ps",
        "module mcu_vga_font (",
        "  input            clk,",
        "  input     [10:0] addr,",
        "  output reg [7:0] q",
        ");",
        "  always @(posedge clk)",
        "    case (addr)",
    ]
    for a, v in enumerate(rom):
        if v:
            out.append(f"      11'h{a:03x}: q <= 8'h{v:02x};")
    out += ["      default: q <= 8'h00;", "    endcase", "endmodule", ""]
    text = "\n".join(out)
    if not os.path.exists(dst) or open(dst).read() != text:
        open(dst, "w").write(text)              # rewritten only when it changes, so make sees no new file
    if hexfile:
        open(hexfile, "w").write("".join(f"{v:02x}\n" for v in rom))


if __name__ == "__main__":
    main()
