#!/usr/bin/env bash
# PIPE-P2b: the traced RD2 pipeline simulator (RD2PipeBootConfig, as generated) with the association checker bound
# into the generated RD2ZynqTop. Same flags, main and models as build-rd2-pipe-sim.sh; the CPU sources are exactly
# rtl/cpu/pipeline/SOURCES.pipe with an include-only search dir.
#   build-assoc-sim.sh <gen dir> <rtl/cpu dir> <fresh outdir> [pipe_fault]
# The generated Verilog is used as is. awaitingRetire has no name of its own in it (FIRRTL calls it _T_<n>): the
# register is found by its source locator -- the line of `val awaitingRetire = RegInit` in the scala that generation
# used (<gen dir>/scala-after/RD2Soc.scala) -- inside module RD2ZynqTop, and must be unique. The checker's bind
# statement is written with that name (bind.sv, kept). [pipe_fault]: a negative build -- a COPY of the generated
# Verilog with .PIPE_FAULT(<k>) added to the tcpu_core_pipe instance (the diff is kept); nothing else changes.
set -u
cd /home/engineer/fpga
WS=/home/engineer/fpga/teaching-cpu-work; FZ=$WS/fpga-zynq; HERE=$(cd "$(dirname "$0")" && pwd)
GEN=${1:?gen dir}; RTL=${2:?rtl/cpu dir}; OUT=${3:?outdir}; PF=${4:-}
V0=$GEN/after-RD2PipeBootConfig/RD2Harness.RD2PipeBootConfig.v; SC=$GEN/scala-after/RD2Soc.scala; MAN=$RTL/pipeline/SOURCES.pipe
for f in $V0 $SC $MAN; do [ -s $f ] || { echo "REFUSE: missing $f"; exit 2; }; done
[ -e "$OUT" ] && { echo "REFUSE: $OUT exists"; exit 2; }
mkdir -p "$OUT/rtl" "$OUT/inc"
V=$V0
if [ -n "$PF" ]; then
  V=$OUT/RD2Harness.RD2PipeBootConfig.pf$PF.v
  sed -E "s/^(\s*tcpu_core_pipe #\()/\1.PIPE_FAULT($PF), /" $V0 > $V
  diff $V0 $V > $OUT/pipe-fault.diff; [ $(grep -c '^>' $OUT/pipe-fault.diff) = 1 ] || { echo "REFUSE: the PIPE_FAULT edit did not change exactly one line"; exit 2; }
fi
L=$(grep -n "val awaitingRetire = RegInit" $SC | cut -d: -f1); [ $(echo "$L" | wc -w) = 1 ] || { echo "REFUSE: awaitingRetire not found once in $SC"; exit 2; }
AW=$(awk -v l="RD2Soc.scala $L:" '/^module /{m=$2} m ~ /^RD2ZynqTop/ && /^\s*reg / && index($0, l) {print $0}' $V | sed -E 's/^\s*reg\s+(\[[^]]*\]\s*)?([A-Za-z0-9_]+);.*/\2/' | sort -u)
[ $(echo "$AW" | wc -w) = 1 ] || { echo "REFUSE: the awaitingRetire register (RD2Soc.scala $L) is not unique in RD2ZynqTop: '$AW'"; exit 2; }
grep -q "assign busy = .*\b$AW\b" $V || { echo "REFUSE: $AW is not a term of RD2ZynqTop's busy"; exit 2; }
cat > $OUT/bind.sv <<BIND
// generated by build-assoc-sim.sh: RD2Soc.scala line $L (val awaitingRetire) = $AW in RD2ZynqTop
bind RD2ZynqTop p2b_assoc_chk assoc (.clock(clock), .reset(reset), .aw_soc($AW), .isFetch(harts_io_obs_isFetch),
  .reqFire(harts_io_physObs_reqFire), .respFire(harts_io_physObs_respFire), .commitValid(harts_io_obs_commitValid),
  .trapValid(harts_io_obs_trapValid), .trapInterrupt(harts_io_obs_trapInterrupt), .commitPc(harts_io_obs_commitPc),
  .trapEpc(harts_io_obs_trapEpc));
BIND
for n in harts_io_obs_isFetch harts_io_physObs_reqFire harts_io_physObs_respFire harts_io_obs_commitValid harts_io_obs_trapValid harts_io_obs_trapInterrupt harts_io_obs_commitPc harts_io_obs_trapEpc; do
  awk '/^module /{m=$2} m ~ /^RD2ZynqTop/' $V | grep -q "\b$n\b" || { echo "REFUSE: RD2ZynqTop has no $n"; exit 2; }; done
SRCS=""
while read -r kind path; do
  case "$kind" in ''|\#*) continue;; esac
  case "$kind" in include) cp "$RTL/$path" "$OUT/inc/";; top|module) cp "$RTL/$path" "$OUT/rtl/"; SRCS="$SRCS $OUT/rtl/$(basename $path)";; *) echo "REFUSE: kind $kind"; exit 2;; esac
done < "$MAN"
cp $HERE/p2b_assoc_chk.sv $OUT/
set +u; source experiments/chipyard-env.sh >/dev/null; set -u
VSRCS="$V $SRCS $OUT/p2b_assoc_chk.sv $OUT/bind.sv $FZ/rocket-chip/vsrc/AsyncResetReg.v $FZ/rocket-chip/vsrc/plusarg_reader.v \
  $FZ/testchipip/vsrc/SimSerial.v $FZ/testchipip/vsrc/SimBlockDevice.v"
RD2SRC=/home/engineer/fpga/experiments/teaching-cpu/reset-drain/rd2/src; M2BT=/home/engineer/fpga/experiments/multicore/m3/tests
CSRCS="$M2BT/m3_main.cpp $RD2SRC/rd2_sim_serial.cc $FZ/testchipip/csrc/SimBlockDevice.cc $FZ/testchipip/csrc/blkdev.cc"
for f in $VSRCS $CSRCS $OUT/inc/*; do sha256sum $f >> "$OUT/inputs.sha256"; done
verilator --cc --exe --build --vpi --no-timing -O3 --x-assign fast --x-initial fast -j 4 \
  -Wno-fatal -Wno-WIDTH -Wno-STMTDLY -Wno-CASEINCOMPLETE -Wno-UNSIGNED -Wno-DECLFILENAME \
  --x-assign unique --top-module RD2Harness \
  +define+PRINTF_COND='$c("Verilated::assertOn()")' +define+STOP_COND='$c("Verilated::assertOn()")' \
  -I$FZ/rocket-chip/vsrc -I$OUT/inc -Mdir "$OUT/obj_dir" -o sim \
  -CFLAGS "-std=c++17 -O2 -I$WS/install/include -I$FZ/testchipip/csrc -DVERILATOR -DM2B_NHARTS=1 -DTEST_HARNESS=VRD2Harness -DHARNESS_TYPE=VRD2Harness -DHARNESS_HEADER='\"VRD2Harness.h\"'" \
  -LDFLAGS "-L$WS/install/lib -lfesvr -Wl,-rpath,$WS/install/lib" \
  $VSRCS $CSRCS > "$OUT/verilator.log" 2>&1; rc=$?
if [ -x "$OUT/obj_dir/sim" ]; then rm -f "$OUT"/obj_dir/*.o "$OUT"/obj_dir/*.d; sha256sum "$OUT/obj_dir/sim" >> "$OUT/inputs.sha256"
  echo "ASSOC_SIM_BUILD_OK aw=$AW $(sha256sum $OUT/obj_dir/sim | cut -c1-16)"; exit 0; fi
echo "ASSOC_SIM_BUILD_FAIL rc=$rc"; grep -E "%Error|error:" "$OUT/verilator.log" | head -10 | cut -c1-220; exit 1
