#!/usr/bin/env python3
"""PIPE-P1: seeded random RV64I programs dense in pipeline hazards. The program has no self-check: the oracle is the
accepted multicycle core's retirement stream and data-request stream on the same program (differential).

Properties by construction: every load/store is inside a 2 KiB data area and aligned (except deliberate misaligned
loads, which trap and are resumed after); every branch/jump goes forward inside the program, except small counted
loops whose counter only this loop writes; nothing reads a cycle counter; the program ends by returning 0.

  gen-hazard.py <seed> <n-instructions> > prog.S

PIPE-P2a copy (p1/scripts/gen-hazard.py is unchanged, so the P1 programs stay byte-identical):
  gen-hazard-p2a.py <seed> <n> [--m] [--c]
  --m  also M instructions (all 13), their sources biased toward recent producers like every other source
  --c  assemble with compressed instructions allowed (.option rvc): the assembler compresses what it can, so the
       stream mixes 16- and 32-bit instructions at 2-byte alignment
"""
import sys, random

EXT_M = '--m' in sys.argv; EXT_C = '--c' in sys.argv
argv = [a for a in sys.argv if not a.startswith('--')]
seed = int(argv[1]); N = int(argv[2]) if len(argv) > 2 else 400
R = random.Random(seed)
POOL = list(range(5, 31))            # x5..x30; x31 = data base, x3 = gp (unused), x1/x2 = ra/sp untouched
BASE = 31
if EXT_C:
    # --c: compressed encodings need x8..x15 (and small offsets from a base in x8..x15), so the data base moves to x8
    # and x9..x15 are drawn three times as often; the loop counter x30 stays outside the compressible set
    BASE = 8
    POOL = [r for r in range(5, 31) if r != 8] + [r for r in range(9, 16)] * 2
LOOPPOOL = sorted(set(r for r in POOL if r != 30))
CR = random.Random(seed * 104729 + 3)   # --c shaping decisions: their own stream
recent = []                          # recently written registers: sources are biased toward them (RAW density)
out = ["# generated by gen-hazard-p2a.py seed=%d n=%d m=%d c=%d" % (seed, N, EXT_M, EXT_C),
       "        .option rvc" if EXT_C else "        .option norvc", "        .text",
       "        .globl main", "main:", "        addi sp, sp, -16", "        sd ra, 0(sp)", "        la x%d, hz_data" % BASE]
lab = [0]
def newlab():
    lab[0] += 1; return "L%d" % lab[0]
def src():
    r = R.random()
    if r < 0.08: return 0                                  # x0 as a source
    if recent and r < 0.75: return R.choice(recent[-3:])   # distance 1..3 producers
    return R.choice(POOL)
def dst():
    d = 0 if R.random() < 0.04 else R.choice(POOL)         # occasionally write x0 (must be discarded)
    if d: recent.append(d); del recent[:-6]
    return d
def x(r): return "x%d" % r
pending = []   # (label, remaining instructions before it is placed)

def emit(s):
    out.append("        " + s)
    for p in pending: p[1] -= 1
    for p in [p for p in pending if p[1] <= 0]:
        out.append(p[0] + ":"); pending.remove(p)

def flush_pending():
    # place every pending forward label here: a branch must never land inside a loop (skipping its counter
    # setup) or between the la and the jalr of an indirect jump
    for p in list(pending): out.append(p[0] + ":"); pending.remove(p)

RALU = ["add", "sub", "and", "or", "xor", "sll", "srl", "sra", "slt", "sltu", "addw", "subw", "sllw", "srlw", "sraw"]
IALU = ["addi", "andi", "ori", "xori", "slti", "sltiu", "addiw"]
SH   = [("slli", 63), ("srli", 63), ("srai", 63), ("slliw", 31), ("srliw", 31), ("sraiw", 31)]
LD = [("ld", 8), ("lw", 4), ("lwu", 4), ("lh", 2), ("lhu", 2), ("lb", 1), ("lbu", 1)]
ST = [("sd", 8), ("sw", 4), ("sh", 2), ("sb", 1)]
BR = ["beq", "bne", "blt", "bge", "bltu", "bgeu"]
MD = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu", "mulw", "divw", "divuw", "remw", "remuw"]
MR = random.Random(seed * 7919 + 1)   # whether and which M instruction: its own stream (without --m the program equals P1)
i = 0
while i < N:
    if EXT_M and MR.random() < 0.15:
        a, b = src(), src(); emit("%s %s, %s, %s" % (MR.choice(MD), x(dst()), x(a), x(b))); i += 1; continue
    k = R.random()
    if k < 0.30:
        a, b = src(), src(); op = R.choice(RALU); d = dst()      # the draw order of the P1 generator
        if EXT_C and d != 0 and CR.random() < 0.4: a = d        # rd == rs1: the c.add / c.sub / c.and ... forms
        emit("%s %s, %s, %s" % (op, x(d), x(a), x(b)))
    elif k < 0.45:
        a = src(); op = R.choice(IALU); d = dst(); imm = R.randint(-2048, 2047)
        if EXT_C and d != 0 and CR.random() < 0.4: a = d; imm = CR.randint(-32, 31)   # the c.addi / c.andi forms
        emit("%s %s, %s, %d" % (op, x(d), x(a), imm))
    elif k < 0.50:
        op, mx = R.choice(SH); a = src(); emit("%s %s, %s, %d" % (op, x(dst()), x(a), R.randint(0, mx)))
    elif k < 0.53:
        emit("%s %s, %d" % (R.choice(["lui", "auipc"]), x(dst()), R.randint(0, 0xfffff)))
    elif k < 0.66:
        op, w = R.choice(LD); off = R.randrange(0, 2048 - w, w)
        emit("%s %s, %d(x%d)" % (op, x(dst()), off, BASE))
    elif k < 0.76:
        op, w = R.choice(ST); off = R.randrange(0, 2048 - w, w)
        emit("%s %s, %d(x%d)" % (op, x(src()), off, BASE))
    elif k < 0.86:
        L = newlab(); a, b = src(), src(); emit("%s %s, %s, %s" % (R.choice(BR), x(a), x(b), L))
        pending.append([L, R.randint(1, 4)])
    elif k < 0.89:
        L = newlab(); emit("jal %s, %s" % (x(dst()), L)); pending.append([L, R.randint(1, 3)])
    elif k < 0.92:
        flush_pending()
        L = newlab(); t = R.choice(POOL); emit("la %s, %s" % (x(t), L)); recent.append(t)
        emit("jalr %s, 0(%s)" % (x(dst()), x(t))); pending.append([L, R.randint(1, 3)])
    elif k < 0.95:
        # a small counted loop with its own counter (x30 is reserved for it here)
        flush_pending()
        L = newlab(); n = R.randint(1, 5)
        emit("li x30, %d" % n); flush_pending(); out.append(L + ":")
        for _ in range(R.randint(1, 3)):
            d = R.choice(LOOPPOOL); a = R.choice(LOOPPOOL); out.append("        add %s, %s, %s" % (x(d), x(a), x(d)))
        out.append("        addi x30, x30, -1"); out.append("        bnez x30, %s" % L)
    elif k < 0.97:
        emit("csrrw %s, mtval, %s" % (x(dst()), x(src())))          # serialising (mtval: the handler owns mscratch)
    elif k < 0.985:
        emit("ecall")                                             # traps; the handler resumes after it
    else:
        emit("ld %s, %d(x%d)" % (x(dst()), R.randrange(1, 2040, 8), BASE))   # misaligned: traps, resumed after
    i += 1
for p in pending: out.append(p[0] + ":")
out += ["        ld ra, 0(sp)", "        addi sp, sp, 16", "        li a0, 0", "        ret",
        "        .data", "        .align 3", "hz_data:"]
out += ["        .dword 0x%016x" % R.getrandbits(64) for _ in range(256)]
print("\n".join(out))
